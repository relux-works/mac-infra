type RootScope string

const (
	RootScopeHome           RootScope = "home"
	RootScopeExplicitTarget RootScope = "explicit_target"
	RootScopeVirtual        RootScope = "virtual"
)

type RootSpec struct {
	Path                   string
	Scope                  RootScope
	Recursive              bool
	RequiresExplicitTarget bool
}

type Category struct {
	ID              CategoryID
	Title           string
	Risk            RiskLevel
	DefaultSelected bool
	Summary         string
	Reason          string
	Roots           []RootSpec
	Patterns        []string
	MinimumAgeDays  int
}

type Policy struct {
	Version    string
	Categories []Category
	Safety     RootSafetyPolicy
}

type DangerousRoot struct {
	Path              string
	Reason            string
	RejectDescendants bool
}

type ExternalVolumePolicy struct {
	Root                               string
	RefuseVolumesRoot                  bool
	RefuseVolumeMountRoots             bool
	AllowChildPaths                    bool
	RequireExplicitTargetForChildPaths bool
	ChildPathRequirements              []string
}

type RootSafetyPolicy struct {
	DangerousRoots             []DangerousRoot
	ExternalVolumes            ExternalVolumePolicy
	RefuseSymlinkRoots         bool
	RefuseSymlinkCandidates    bool
	RequireRealpathContainment bool
	RequireUserOwnedRoots      bool
	RequireUserOwnedCandidates bool
}

type RootDecision struct {
	Path                        string
	Allowed                     bool
	Dangerous                   bool
	Reason                      string
	ExternalVolumeChild         bool
	RequiresExplicitTarget      bool
	RequiresOwnershipCheck      bool
	RequiresSymlinkCheck        bool
	RequiresRealpathContainment bool
}

