func (policy RootSafetyPolicy) EvaluateRoot(path string, homeDir string) RootDecision {
	cleanPath := filepath.Clean(path)
	decision := RootDecision{
		Path:                        cleanPath,
		Allowed:                     true,
		RequiresOwnershipCheck:      policy.RequireUserOwnedRoots,
		RequiresSymlinkCheck:        policy.RefuseSymlinkRoots,
		RequiresRealpathContainment: policy.RequireRealpathContainment,
	}

	if dangerous, ok := policy.matchDangerousRoot(cleanPath, homeDir); ok {
		decision.Allowed = false
		decision.Dangerous = true
		decision.Reason = dangerous.Reason
		return decision
	}

	volumeRoot := filepath.Clean(policy.ExternalVolumes.Root)
	if policy.ExternalVolumes.RefuseVolumesRoot && cleanPath == volumeRoot {
		decision.Allowed = false
		decision.Dangerous = true
		decision.Reason = "external volume mount root is never a cleanup target"
		return decision
	}

	if volumeName, rest, ok := splitExternalVolumePath(cleanPath, volumeRoot); ok {
		if policy.ExternalVolumes.RefuseVolumeMountRoots && rest == "" {
			decision.Allowed = false
			decision.Dangerous = true
			decision.Reason = "external volume root " + volumeName + " is never default-selected or cleaned as a whole"
			return decision
		}

		decision.ExternalVolumeChild = true
		decision.RequiresExplicitTarget = policy.ExternalVolumes.RequireExplicitTargetForChildPaths
		if !policy.ExternalVolumes.AllowChildPaths {
			decision.Allowed = false
			decision.Dangerous = true
			decision.Reason = "external volume child paths are disabled by policy"
		}
	}

	return decision
}

func (policy RootSafetyPolicy) matchDangerousRoot(path string, homeDir string) (DangerousRoot, bool) {
	cleanHome := filepath.Clean(homeDir)
	for _, root := range policy.DangerousRoots {
		if root.Path == "$HOME" {
			if homeDir != "" && path == cleanHome {
				return root, true
			}
			continue
		}
		rootPath := filepath.Clean(root.Path)
		if path == rootPath || root.RejectDescendants && hasPathPrefix(path, rootPath) {
			return root, true
		}
	}
	return DangerousRoot{}, false
}

func hasPathPrefix(path string, root string) bool {
	if root == string(filepath.Separator) {
		return false
	}
	return strings.HasPrefix(path, root+string(filepath.Separator))
}

func splitExternalVolumePath(path string, volumeRoot string) (volumeName string, rest string, ok bool) {
	prefix := volumeRoot + string(filepath.Separator)
	if !strings.HasPrefix(path, prefix) {
		return "", "", false
	}

	remaining := strings.TrimPrefix(path, prefix)
	parts := strings.SplitN(remaining, string(filepath.Separator), 2)
	if parts[0] == "" {
		return "", "", false
	}
	if len(parts) == 1 {
		return parts[0], "", true
	}
	return parts[0], parts[1], true
}
